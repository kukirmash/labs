#ifndef ID_H
#define ID_H

//----------------------------------------------------------------------------------------------------------
#include <string>

//----------------------------------------------------------------------------------------------------------
class Id
{
    u_int32_t id_;
    std::string name_;

public:
    Id(u_int32_t id = 0, std::string name = "")
    {
        id_ = id;
        name_ = name;
    }
    ~Id()
    {
    }

    // Геттеры
    u_int32_t GetId() const { return id_; }
    std::string GetName() const { return name_; }
};

//----------------------------------------------------------------------------------------------------------
#endif // ID_H