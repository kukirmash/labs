package cpu

import "os_model/pkg/process"

// ----------------------------------------------------------------------------------
// SystemCallHandler — интерфейс системных вызовов, которые АЛУ адресует ядру.
//
// Интерфейс объявлен на стороне потребителя (consumer-side interface), чтобы
// пакет cpu не зависел от пакета kernel: ядро реализует его структурно.
type SystemCallHandler interface {
	// RequestIO инициирует операцию ввода-вывода для процесса:
	// ядро переводит процесс в состояние «Блокирован по обращению ко вводу»
	// и запускает устройство ввода-вывода.
	RequestIO(psw *process.PSW)

	// TerminateProcess завершает процесс: удаляет запись из таблицы процессов,
	// освобождает память и увеличивает счётчик выполненных заданий.
	TerminateProcess(pswID int)
}

// ----------------------------------------------------------------------------------
// ALU — арифметико-логическое устройство.
type ALU struct {
}

// ----------------------------------------------------------------------------------
// DoOperation выполняет операцию команды над операндами.
//
//   - OpCompute — двухместная вычислительная операция (в модели — сложение
//     операндов); выполняется за один такт, результат записывается в PSW.
//   - OpIO — порождает системный процесс инициализации устройства
//     ввода-вывода, процесс переводится в состояние «Инициализация IO»,
//     затем ядро блокирует его до завершения операции.
//   - OpEnd — порождает системный процесс завершения задания.
func (ALU) DoOperation(cmd Command, psw *process.PSW, sys SystemCallHandler) {
	if psw == nil {
		return
	}

	switch cmd.Code {
	case OpCompute:
		// Чтение операндов, выполнение операции и запись результата
		// в аппаратную память (моделируется регистром LastResult в PSW).
		psw.LastResult = cmd.Arg1 + cmd.Arg2

	case OpIO:
		psw.IORequestTicks = cmd.Arg1
		psw.State = process.StateInitIO
		if sys != nil {
			sys.RequestIO(psw)
		}

	case OpEnd:
		psw.State = process.StateEndIO
		if sys != nil {
			sys.TerminateProcess(psw.ID)
		}
	}
}
