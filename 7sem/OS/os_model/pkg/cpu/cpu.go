// Package cpu моделирует процессор машины фон Неймана: устройство управления
// (выборка, дешифрация команд и аппаратный счётчик PC) и арифметико-логическое
// устройство (АЛУ).
package cpu

import "os_model/pkg/process"

// ----------------------------------------------------------------------------------
// State — состояние процессора.
type State string

const (
	CPUStateWork State = "Работа"
	CPUStateWait State = "Ожидание"
)

// ----------------------------------------------------------------------------------
// CPU — центральный процессор.
type CPU struct {
	PC          int     // аппаратный счётчик команд
	Speed       float64 // тактовая частота (тактов/сек)
	State       State   // состояние: «Работа» или «Ожидание»
	ALU         ALU     // арифметико-логическое устройство
	LastCommand Command // последняя выбранная команда (для индикации)
	HasCommand  bool    // была ли выполнена хотя бы одна команда
}

// ----------------------------------------------------------------------------------
// New создаёт процессор в состоянии ожидания с частотой 1 такт/с.
func New() *CPU {
	return &CPU{
		PC:    0,
		Speed: 1.0,
		State: CPUStateWait,
	}
}

// ----------------------------------------------------------------------------------
// Reset сбрасывает регистры процессора.
func (c *CPU) Reset() {
	c.PC = 0
	c.LastCommand = Command{}
	c.HasCommand = false
	c.State = CPUStateWait
}

// ----------------------------------------------------------------------------------
// Tick выполняет один такт работы процессора по алгоритму машины фон Неймана:
//
//  1. чтение команды из памяти по адресу счётчика команд (генерация команды);
//  2. увеличение аппаратного счётчика команд (длина команды = 1);
//  3. распознавание команды (дешифрация кода операции);
//  4. чтение операндов из аппаратной памяти;
//  5. выполнение операции на АЛУ;
//  6. запись результата операции в аппаратную память.
//
// Шаги 3–6 выполняет ALU.DoOperation, которому передаётся указатель на PSW
// активного процесса и обработчик системных вызовов ядра.
func (cpu *CPU) Tick(psw *process.PSW, sys SystemCallHandler) {
	if psw == nil || psw.State != process.StateActive {
		cpu.State = CPUStateWait
		return
	}

	cpu.State = CPUStateWork

	// 1. Чтение команды из памяти по адресу аппаратного счётчика команд.
	cmd := psw.GenerateNextCommand()
	cpu.LastCommand = cmd
	cpu.HasCommand = true

	// 2. Увеличение аппаратного счётчика команд (длина команды = 1).
	psw.PC++
	cpu.PC = psw.PC

	// 3–6. Дешифрация, чтение операндов, выполнение, запись результата.
	cpu.ALU.DoOperation(cmd, psw, sys)
}
