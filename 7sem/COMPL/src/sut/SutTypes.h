#ifndef SUT_TYPES_H
#define SUT_TYPES_H

//----------------------------------------------------------------------------------------------------------
#include <string>
#include "../scanner/Token.h"
#include "../scanner/TableId_Elem.h"

//----------------------------------------------------------------------------------------------------------
// Тип элемента таблицы разбора
enum class LRElType : int
{
    Err = 0,    // ошибка
    Shift = 1,  // перенос
    Reduct = 2, // свертка
    Stop = 3    // останов
};

//----------------------------------------------------------------------------------------------------------
// Элемент таблицы разбора
struct LRElem
{
    LRElType type = LRElType::Err;
    int par = 0;     // номер состояния (перенос) или длина правой части (свертка)
    int left = 0;    // код нетерминала левой части продукции
    int act = 0;     // номер семантического действия (0 — действия нет)
    int numProd = 0; // номер продукции (для наглядности)
};

//----------------------------------------------------------------------------------------------------------
// Информация о типе
struct TypeInfo
{
    TypeCode code = typeVoid;
    int width = 0;
    int fields = -1; // индекс таблицы полей для типа-записи
};

//----------------------------------------------------------------------------------------------------------
inline bool TypeEqual(const TypeInfo &a, const TypeInfo &b)
{
    return a.code == b.code && a.fields == b.fields;
}

//----------------------------------------------------------------------------------------------------------
inline TypeInfo LogicalType()
{
    TypeInfo t;
    t.code = typeLogical;
    t.width = wLogical;
    return t;
}

//----------------------------------------------------------------------------------------------------------
// Значение в стеке атрибутов: либо тип, либо целое (адрес, указатель, код операции)
struct Attr
{
    enum Kind
    {
        Int,
        Type
    };

    Kind kind = Int;
    int value = 0;
    TypeInfo type;

    static Attr makeInt(int v)
    {
        Attr a;
        a.kind = Int;
        a.value = v;
        return a;
    }

    static Attr makeType(const TypeInfo &t)
    {
        Attr a;
        a.kind = Type;
        a.type = t;
        return a;
    }
};

//----------------------------------------------------------------------------------------------------------
#endif // SUT_TYPES_H
